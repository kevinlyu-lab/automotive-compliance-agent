"""SOTIF (ISO 21448:2022) 分析：CTA 因果树、STPA、SOTIF 导向 FMEA 的离线初稿。

三种方法各自成体系，互不共用表格：
- CTA：从整车危害（顶事件）向下展开功能不足 / 输出不足 / 触发条件，区分 AND/OR，
  由因果树推出最小割集，并显式排除随机硬件故障（那属于 ISO 26262 FTA）。
- STPA：损失与整车危害 → 系统边界与控制结构 → 控制动作与反馈 → 四类不安全控制行为
  → 原因场景（不足条件 + 因果因素）→ 安全约束。
- FMEA：按功能/系统要素逐项分析「功能定义不足或性能局限 → 触发条件 → 输出不足
  → 整车危害行为 → 危害事件 → 措施 → 验证方式」，不把性能局限写成硬件损坏。

本模块只做保守的离线初稿：阈值、接口、传感器型号一律标注为示例/待确认。
"""
