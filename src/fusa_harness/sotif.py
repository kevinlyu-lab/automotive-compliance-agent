def stpa_draft(feature: str, instruction: str, source_rows: list[dict]) -> dict:
    ctx = describe(feature, instruction)
    family = ctx["family"]
    name = ctx["name"]

    losses = []
    for hid, loss, hazard, event, stakeholder, constraint in _STPA_HAZARDS[family]:
        losses.append({
            "编号": hid, "损失（Loss）": loss,
            "整车危害（Hazard）": f"{hazard}（{name}）",
            "危害事件": f"{ctx['scenario']}下：{event}",
            "涉及利益相关者": stakeholder,
            "初步安全约束": constraint,
        })
    if source_rows:
        for index, row in enumerate(source_rows[:5], 1):
            hazard_text = str(row.get("Hazard") or row.get("潜在效应") or row.get("整车影响") or "").strip()
            if hazard_text:
                losses.append({
                    "编号": f"H{len(losses) + 1}", "损失（Loss）": "L1 人员伤亡（来自来源分析）",
                    "整车危害（Hazard）": hazard_text, "危害事件": str(row.get("Potential Effect") or hazard_text),
                    "涉及利益相关者": "驾驶员/乘员/其他交通参与者",
                    "初步安全约束": "系统应避免该危害事件发生",
                })

    structure = [{
        "层级": level, "控制器或要素": element, "控制动作（Control Action）": action,
        "受控过程": process, "反馈（Feedback）": feedback, "接口与环境": interface, "边界假设": assumption,
    } for level, element, action, process, feedback, interface, assumption in _STPA_STRUCTURE]

    ucas = [{
        "UCA 编号": uid, "控制器": controller, "控制动作": action, "UCA 类型": kind,
        "不安全控制行为描述": desc, "关联整车危害": hazard, "发生情境（最坏条件）": context,
        "对应安全约束": sc,
    } for uid, controller, action, kind, desc, hazard, context, sc in _STPA_UCAS[family]]

    causes = [{
        "场景编号": cid, "关联 UCA": uca, "不足条件（IC）": ic, "因果因素（CF）": cf,
        "因素类型": kind, "说明与证据": note,
    } for cid, uca, ic, cf, kind, note in _STPA_CAUSES[family]]

    constraints = [{
        "约束编号": scid, "关联 UCA": uca, "安全约束": text, "约束类型": kind,
        "分配到要素": allocation, "验证方式": verify,
    } for scid, uca, text, kind, allocation, verify in _STPA_SCS[family]]

    notes = [
        "STPA 将安全视为控制问题：不安全控制行为（UCA）是分析对象，四类 UCA 已逐一覆盖（未提供 / 提供导致危害 / 时序错误 / 持续时间错误）。",
        "原因场景按「不足条件（IC）→ 因果因素（CF）」组织，CF 类型沿用 ISO 21448 的功能不足、输出不足与触发条件。",
        f"控制结构按「驾驶员—功能控制器—感知融合—执行器—车辆—环境」通用层级补全，需按项目实际架构替换（当前分析对象：{name}）。",
        "UCA 与安全约束应逐条对应，安全约束可作为后续 FSR/TSR 或 SOTIF 需求的输入。",
    ]
    if source_rows:
        notes.append(f"已结合来源分析的 {min(len(source_rows), 5)} 条危害补充整车危害列表。")

    return {
        "sections": [
            {"name": "损失与危害", "fields": STPA_LOSS_FIELDS, "rows": losses},
            {"name": "控制结构", "fields": STPA_STRUCT_FIELDS, "rows": structure},
            {"name": "不安全控制行为", "fields": STPA_UCA_FIELDS, "rows": ucas},
            {"name": "原因场景", "fields": STPA_CAUSE_FIELDS, "rows": causes},
            {"name": "安全约束", "fields": STPA_SC_FIELDS, "rows": constraints},
        ],
        "rows": ucas,
        "notes": notes,
    }

