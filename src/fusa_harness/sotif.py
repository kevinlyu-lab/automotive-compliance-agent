def fmea_draft(feature: str, instruction: str, source_rows: list[dict]) -> dict:
    ctx = describe(feature, instruction)
    family = ctx["family"]
    name = ctx["name"]
    rows = []
    for index, item in enumerate(_FMEA_ELEMENTS[family] + _FMEA_COMMON, 1):
        element, level, limitation, trigger, output, behavior, event, control, measure, verify = item
        rows.append({
            "编号": f"F-{index:03d}",
            "分析对象或功能": f"{element}（{name} 相关）",
            "要素层级": level,
            "功能定义不足或性能局限": limitation,
            "触发条件": trigger,
            "输出不足": output,
            "整车危害行为": behavior,
            "危害事件": f"{ctx['scenario']}：{event}",
            "现有控制措施": control,
            "SOTIF 措施": measure,
            "验证方式": verify,
            "残余风险说明": "措施有效性需以验证结果评估；未覆盖的触发条件按已知不安全场景管理",
        })
    for row in source_rows[:8]:
        hazard = str(row.get("Hazard") or row.get("整车影响") or "").strip()
        if not hazard:
            continue
        rows.append({
            "编号": f"F-{len(rows) + 1:03d}",
            "分析对象或功能": f"来源分析条目 {row.get('编号', '')}".strip(),
            "要素层级": "系统要素",
            "功能定义不足或性能局限": str(row.get("安全措施") or "来源分析未给出功能不足描述（待确认）"),
            "触发条件": str(row.get("环境条件") or row.get("道路条件") or ctx["scenario"]),
            "输出不足": str(row.get("Potential Effect") or "来源分析未给出输出不足（待确认）"),
            "整车危害行为": hazard,
            "危害事件": str(row.get("Potential Effect") or hazard),
            "现有控制措施": str(row.get("现有控制") or "待确认"),
            "SOTIF 措施": str(row.get("安全措施") or "待补充"),
            "验证方式": "按来源分析条目对应的验证计划执行（待确认）",
            "残余风险说明": "由来源分析继承，需复核",
        })

    notes = [
        "本表为 SOTIF 归纳分析：每一项都是「功能定义不足 / 性能局限 → 触发条件 → 输出不足 → 整车危害行为 → 危害事件」，不是硬件随机失效。",
        "摄像头在逆光下能力受限、雷达对静止目标信噪比不足等属于性能局限，禁止表述为“硬件损坏/元器件失效”（那属于 ISO 26262 FMEA）。",
        f"未提供系统架构时按“{ctx['scenario']} + 感知/决策/执行/人机”通用要素补全，需在架构确定后替换。",
        "措施与验证方式中的阈值、试验里程为示例值，需按项目 SOTIF 验证计划确认。",
    ]
    if source_rows:
        notes.append(f"已从来源分析引入 {min(len(source_rows), 8)} 条危害作为危害事件列。")

    return {
        "sections": [{"name": "FMEA", "fields": FMEA_FIELDS, "rows": rows}],
        "rows": rows,
        "notes": notes,
    }


def sotif_draft(task: str, feature: str, instruction: str, source_rows: list[dict]) -> dict:
    if task == "CTA":
        return cta_draft(feature, instruction, source_rows)
    if task == "STPA":
        return stpa_draft(feature, instruction, source_rows)
    if task == "FMEA":
        return fmea_draft(feature, instruction, source_rows)
    raise ValueError(f"不支持的 SOTIF 任务：{task}")
