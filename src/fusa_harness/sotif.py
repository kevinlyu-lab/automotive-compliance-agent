FEATURE_FAMILY = {
    "LCC": "lateral", "ALC": "lateral", "LKA": "lateral", "NOA": "lateral",
    "ACC": "longitudinal", "AEB": "longitudinal",
    "APA": "generic",
}


def family_of(text: str) -> str:
    """按功能语义判定横向 / 纵向 / 通用，供 CTA 与 FMEA 选择失效链。"""
    if re.search("|".join(re.escape(word) for word in LATERAL_WORDS), text, re.I):
        return "lateral"
    if re.search("|".join(re.escape(word) for word in LONGITUDINAL_WORDS), text, re.I):
        return "longitudinal"
    return "generic"


def scenario_of(text: str) -> str:
    for words, label in SCENARIOS:
        if any(word.lower() in text.lower() for word in words):
            return label
    return "高速公路（默认场景，待项目确认）"


def describe(feature: str, instruction: str) -> dict[str, str]:
    name = FEATURE_NAMES.get(feature.upper(), feature)
    family = FEATURE_FAMILY.get(feature.upper()) or family_of(f"{feature} {instruction}")
    scenario = scenario_of(instruction)
    return {
        "feature": feature,
        "name": name,
        "family": family,
        "scenario": scenario,
        "item": f"{name}（分析对象：{feature or name}）",
    }

