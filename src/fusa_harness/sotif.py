def _cta_spec(feature: str, instruction: str) -> dict:
    """组装 CTA 的顶事件、因果树、底事件与最小割集。"""
    ctx = describe(feature, instruction)
    family = ctx["family"]
    name = ctx["name"]
    if family == "lateral":
        top = f"本车产生非预期横向运动，与相邻车道车辆或道路边界发生碰撞"
        consequence = "侧碰、刮擦或驶出车道后与护栏/路侧设施碰撞"
    elif family == "longitudinal":
        top = f"本车产生非预期纵向运动（异常制动/加速或制动不足），导致追尾或被追尾"
        consequence = "追尾、被追尾或多车连环碰撞"
    else:
        top = f"{name}的输出不足导致本车与交通参与者或道路设施发生碰撞"
        consequence = "碰撞或车辆失控"

    branches = _CTA_BRANCHES[family]
    nodes: list[dict] = [{
        "节点编号": "T0", "父节点": "—", "节点类型": "顶事件", "逻辑门": "OR",
        "节点描述": top, "不足类型": "整车危害（顶事件）", "证据或假设": f"场景：{ctx['scenario']}；来源：ISO 21448:2022 第 7 章",
    }]
    leaves: list[dict] = []
    for branch_id, gate, branch_desc, branch_leaves in branches:
        nodes.append({
            "节点编号": branch_id, "父节点": "T0", "节点类型": "中间事件", "逻辑门": gate,
            "节点描述": branch_desc, "不足类型": "功能不足分支", "证据或假设": "由功能不足分析得到的分支假设",
        })
        for leaf_id, desc, category, element, trigger, output, measure, verify, evidence in branch_leaves:
            leaves.append({
                "底事件编号": leaf_id, "事件类别": category, "事件描述": desc, "所属系统要素": element,
                "关联触发条件": trigger, "导致的输出不足": output,
                "是否属于 SOTIF 范围": "是（非硬件随机失效）",
                "处理措施": measure, "验证方式": verify, "_evidence": evidence,
            })
            nodes.append({
                "节点编号": leaf_id, "父节点": branch_id, "节点类型": "底事件", "逻辑门": "—",
                "节点描述": desc, "不足类型": category, "证据或假设": evidence,
            })
    return {
        "top": {"编号": "T0", "顶事件（整车危害）": f"H-{feature or 'SYS'}-01：{top}",
                "危害事件": f"{ctx['scenario']}下，{name}输出不足引发{consequence}",
                "相关功能": name, "运行场景": ctx["scenario"], "危害后果": consequence,
                "SOTIF 适用性": "适用：由功能定义不足、性能局限或合理可预见误用引起，非硬件随机失效",
                "分析边界与假设": "仅展开 SOTIF 因果链；随机硬件失效、软件缺陷导致的失效不在本树内（见 ISO 26262 FTA/FMEA）"},
        "tree": nodes, "leaves": leaves, "branches": branches,
    }


def cut_sets_from_tree(tree_rows: list[dict]) -> list[dict]:
    """由「因果树」分段反推最小割集：支持 AND/OR 门，并做超集消减。

    供模型产出与离线初稿统一使用，保证割集一定与因果树一致、可复算。
    """
    nodes: dict[str, dict] = {}
    for row in tree_rows:
        node_id = str(row.get("节点编号") or "").strip()
        if node_id and node_id not in nodes:
            nodes[node_id] = row
    if not nodes:
        return []
    children: dict[str, list[str]] = {node_id: [] for node_id in nodes}
    roots: list[str] = []
    for node_id, row in nodes.items():
        parent = str(row.get("父节点") or "").strip()
        if parent in nodes and parent != node_id:
            children[parent].append(node_id)
        else:
            roots.append(node_id)

    def compute(node_id: str, depth: int = 0) -> list[frozenset[str]]:
        if depth > 20:
            return [frozenset([node_id])]
        kids = children.get(node_id, [])
        if not kids:
            return [frozenset([node_id])]
        parts = [compute(kid, depth + 1) for kid in kids]
        gate = str(nodes[node_id].get("逻辑门") or "").strip().upper()
        if gate.startswith("AND"):
            result = [frozenset()]
            for part in parts:
                result = [left | right for left in result for right in part]
                if len(result) > 500:
                    break
            return result
        # OR 或未标注：任一子节点成立即可
        return [item for part in parts for item in part]

    raw = compute(roots[0] if roots else next(iter(nodes)))
    minimal: list[frozenset[str]] = []
    for item in sorted(raw, key=len):
        if not any(existing <= item for existing in minimal):
            minimal.append(item)

    rows = []
    for index, cut in enumerate(sorted(minimal, key=lambda item: (len(item), sorted(item))), 1):
        ordered = sorted(cut)
        expression = " · ".join(ordered) if len(ordered) > 1 else ordered[0]
        descriptions = [str(nodes[node].get("节点描述") or node)[:30] for node in ordered]
        rows.append({
            "割集编号": f"MCS-{index:03d}",
            "阶数": f"{len(ordered)} 阶",
            "布尔表达式": expression,
            "组成底事件": "；".join(
                f"{node}（{str(nodes[node].get('不足类型') or '底事件')}）" for node in ordered
            ),
            "对应顶事件": str(nodes[roots[0]].get("节点编号") if roots else "T0"),
            "SOTIF 处理优先级": f"第 {index} 优先（割集阶数越低越优先）",
            "说明": (
                f"{descriptions[0]} 单独成立即导致顶事件发生" if len(ordered) == 1
                else "、".join(descriptions) + " 同时成立时顶事件发生"
            ),
            "缓解与验证要点": "见对应底事件的处理措施与验证方式",
        })
    return rows


def _cut_sets(branches) -> list[list[str]]:
    """由「顶事件 OR 分支 / 分支 AND 或 OR 叶子」结构推出最小割集（已做超集消减）。"""
    raw: list[frozenset[str]] = []
    for _, gate, _, leaves in branches:
        if gate == "AND":
            raw.append(frozenset(leaf[0] for leaf in leaves))
        else:  # OR 分支：每个叶子单独构成一阶割集
            raw.extend(frozenset([leaf[0]]) for leaf in leaves)
    minimal: list[frozenset[str]] = []
    for item in sorted(raw, key=len):
        if not any(existing <= item for existing in minimal):
            minimal.append(item)
    return [sorted(item) for item in minimal]


def cta_draft(feature: str, instruction: str, source_rows: list[dict]) -> dict:
    spec = _cta_spec(feature, instruction)
    ctx = describe(feature, instruction)
    cuts = _cut_sets(spec["branches"])

    leaf_by_id = {leaf["底事件编号"]: leaf for leaf in spec["leaves"]}
    cut_rows = []
    for index, cut in enumerate(sorted(cuts, key=lambda item: (len(item), item)), 1):
        involved = [leaf_by_id[item] for item in cut]
        cut_rows.append({
            "割集编号": f"MCS-{index:03d}",
            "阶数": f"{len(cut)} 阶",
            "布尔表达式": " · ".join(cut) if len(cut) > 1 else cut[0],
            "组成底事件": "；".join(f"{item}（{leaf_by_id[item]['事件类别']}）" for item in cut),
            "对应顶事件": "T0",
            "SOTIF 处理优先级": f"第 {index} 优先（割集阶数越低越优先）",
            "说明": (
                f"{leaf_by_id[cut[0]]['事件描述']} 单独成立即导致顶事件发生" if len(cut) == 1
                else "、".join(leaf_by_id[item]["事件描述"][:28] for item in cut) + " 同时成立时顶事件发生"
            ),
            "缓解与验证要点": "；".join(sorted({leaf_by_id[item]['处理措施'][:40] for item in cut})),
        })

    notes = [
        "CTA 为演绎分析：从整车危害（顶事件）向下展开功能不足、输出不足与触发条件，最小割集用于确定 SOTIF 处理优先级。",
        "本树不包含随机硬件失效与系统性软件缺陷的失效路径（那属于 ISO 26262 FTA/FMEA），仅保留 SOTIF 因果链。",
        f"未提供的系统架构信息按“{ctx['scenario']} + 感知/决策/执行/人机四层”通用结构补全，需在架构确定后替换。",
        "底事件中的阈值、传感器指标为示例值，需结合项目 ODD 与标定数据确认。",
    ]
    if source_rows:
        ids = [str(row.get("编号") or "") for row in source_rows if row.get("编号")]
        notes.append(f"已关联来源分析条目：{', '.join(ids[:20])}；顶事件与危害事件应与其保持一致。")

    return {
        "sections": [
            {"name": "顶事件", "fields": CTA_TOP_FIELDS, "rows": [spec["top"]]},
            {"name": "因果树", "fields": CTA_TREE_FIELDS, "rows": spec["tree"]},
            {"name": "底事件", "fields": CTA_LEAF_FIELDS, "rows": [
                {key: value for key, value in leaf.items() if not key.startswith("_")} for leaf in spec["leaves"]
            ]},
            {"name": "最小割集", "fields": CTA_CUT_FIELDS, "rows": cut_rows},
        ],
        "rows": [{key: value for key, value in leaf.items() if not key.startswith("_")} for leaf in spec["leaves"]],
        "notes": notes,
    }

